#!/usr/bin/env python3
"""Convert a simple Inkscape SVG (paths made of m/l/h/v/c/s/z, flat fills and strokes, one matrix transform) into the
vector-logo header format used by congobongo.cpp (cubic Beziers).  Usage: svg_to_logo.py in.svg out.h PREFIX"""
import re, sys, xml.etree.ElementTree as ET

def parse_color(c):
    if c is None or c == 'none': return 0
    c = c.strip()
    if c.startswith('#'):
        if len(c) == 4: c = '#' + ''.join(ch * 2 for ch in c[1:])
        return 0xFF000000 | int(c[1:], 16)
    raise SystemExit('unsupported colour ' + c)

def mat(t):
    if not t: return (1, 0, 0, 1, 0, 0)
    m = re.match(r'matrix\(([^)]*)\)', t)
    if not m: raise SystemExit('unsupported transform ' + t)
    return tuple(float(v) for v in re.split(r'[ ,]+', m.group(1).strip()))

def mul(a, b):   # a applied after b
    return (a[0]*b[0]+a[2]*b[1], a[1]*b[0]+a[3]*b[1], a[0]*b[2]+a[2]*b[3], a[1]*b[2]+a[3]*b[3],
            a[0]*b[4]+a[2]*b[5]+a[4], a[1]*b[4]+a[3]*b[5]+a[5])

def tokens(d):
    for m in re.finditer(r'([MmLlHhVvCcSsZz])|(-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?)', d):
        yield m.group(1) or float(m.group(2))

def parse_path(d):
    toks = list(tokens(d)); i = 0; subs = []; cur = None; x = y = sx = sy = 0.0; cmd = None; last_c2 = None
    def num():
        nonlocal i; v = toks[i]; i += 1; return v
    while i < len(toks):
        if isinstance(toks[i], str): cmd = toks[i]; i += 1
        rel = cmd.islower(); c = cmd.lower()
        if c == 'z':
            if cur: cur['closed'] = True
            x, y = sx, sy; last_c2 = None; continue
        if c == 'm':
            nx, ny = num(), num()
            if rel: nx += x; ny += y
            x, y = nx, ny; sx, sy = x, y; cur = {'start': (x, y), 'segs': [], 'closed': False}; subs.append(cur)
            cmd = 'l' if rel else 'L'; last_c2 = None; continue
        if cur is None: raise SystemExit('path without moveto')
        if c in 'lhv':
            if c == 'l': nx, ny = num(), num(); nx, ny = (nx + x, ny + y) if rel else (nx, ny)
            elif c == 'h': nx = num(); nx = nx + x if rel else nx; ny = y
            else: ny = num(); ny = ny + y if rel else ny; nx = x
            cur['segs'].append(((x + (nx - x) / 3, y + (ny - y) / 3), (x + 2 * (nx - x) / 3, y + 2 * (ny - y) / 3), (nx, ny)))
            x, y = nx, ny; last_c2 = None
        elif c == 'c':
            v = [num() for _ in range(6)]
            if rel: v = [v[0]+x, v[1]+y, v[2]+x, v[3]+y, v[4]+x, v[5]+y]
            cur['segs'].append(((v[0], v[1]), (v[2], v[3]), (v[4], v[5]))); last_c2 = (v[2], v[3]); x, y = v[4], v[5]
        elif c == 's':
            v = [num() for _ in range(4)]
            if rel: v = [v[0]+x, v[1]+y, v[2]+x, v[3]+y]
            c1 = (2 * x - last_c2[0], 2 * y - last_c2[1]) if last_c2 else (x, y)
            cur['segs'].append((c1, (v[0], v[1]), (v[2], v[3]))); last_c2 = (v[0], v[1]); x, y = v[2], v[3]
        else: raise SystemExit('unsupported command ' + cmd)
    return subs

def main():
    src, out, pre = sys.argv[1:4]
    root = ET.parse(src).getroot()
    ns = '{http://www.w3.org/2000/svg}'
    vb = [float(v) for v in root.get('viewBox').split()]
    paths = []; subs_all = []; pts = []
    def walk(el, inh, m):
        st = dict(inh)
        for k in ('fill', 'stroke', 'stroke-width', 'stroke-linecap'):
            if el.get(k) is not None: st[k] = el.get(k)
        m = mul(m, mat(el.get('transform')))
        if el.tag == ns + 'path':
            if el.get('id') == 'path12': return        # the black backdrop rectangle
            fill = parse_color(st.get('fill', '#000')); stroke = parse_color(st.get('stroke')); sw = float(st.get('stroke-width', 0))
            sc = (abs(m[0] * m[3] - m[1] * m[2])) ** 0.5
            first = len(subs_all)
            for sp in parse_path(el.get('d')):
                if not sp['segs']: continue
                T = lambda p: (m[0]*p[0]+m[2]*p[1]+m[4], m[1]*p[0]+m[3]*p[1]+m[5])
                subs_all.append((len(pts) // 2, len(sp['segs']), 1 if sp['closed'] else 0))
                pts.extend(T(sp['start']))
                for seg in sp['segs']:
                    for p in seg: pts.extend(T(p))
            if len(subs_all) > first:
                paths.append((fill, stroke if sw > 0 else 0, sw * sc, 1 if st.get('stroke-linecap') == 'round' else 0, first, len(subs_all) - first))
        for ch in el: walk(ch, st, m)
    walk(root, {}, (1, 0, 0, 1, 0, 0))
    with open(out, 'w') as f:
        f.write('// Vector logo (cubic Beziers) generated by tools/svg_to_logo.py from the supplied SVG.\n')
        f.write('// Coordinates are in the SVG viewBox units.  Same format as congo_logo_data.h (types come from there).\n#pragma once\n#include "congo_logo_data.h"\n')
        f.write('static const float %s_VB_W = %.4ff, %s_VB_H = %.4ff;\n' % (pre, vb[2], pre, vb[3]))
        f.write('static const LogoPath %s_PATHS[] = {\n' % pre)
        for p in paths: f.write('\t{ 0x%08X, 0x%08X, %.4ff, %d, %d, %d },\n' % p)
        f.write('};\nstatic const LogoSub %s_SUBS[] = {\n' % pre)
        for s in subs_all: f.write('\t{ %d, %d, %d },\n' % s)
        f.write('};\nstatic const float %s_PTS[] = {\n' % pre)
        for i in range(0, len(pts), 12): f.write('\t' + ', '.join('%.3ff' % v for v in pts[i:i+12]) + ',\n')
        f.write('};\n')
    print(len(paths), 'paths', len(subs_all), 'subpaths', len(pts) // 2, 'points')
main()
